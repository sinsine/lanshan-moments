export function releaseUrl(version: string): string {
  // 0.4.4 was built locally but folded into the v0.5.0 release; send its
  // “查看 Release” link to the release list instead of a missing tag.
  if (version.replace(/^v/i, '') === '0.4.4') {
    return 'https://github.com/sinsine/lanshan-moments/releases'
  }
  const tag = version.startsWith('v') ? version : `v${version}`
  return `https://github.com/sinsine/lanshan-moments/releases/tag/${tag}`
}
